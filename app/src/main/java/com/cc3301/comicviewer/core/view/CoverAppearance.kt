package com.cc3301.comicviewer.core.view

/**
 * 封面出图口径（票 #108 E2-B，由 [CoverAppearanceTest] 锁定）。
 *
 * 维护者现象：书柜/浏览页的封面会以三种形态混着出现——立刻就有、灰底「加载中」、以及「从无到有慢慢加载出来」。
 * 口径统一成**两态**：骨架占位（盒子的底色，位图未到位时恒在）→ 出图淡入。
 * 淡入时长是这条口径里的常数（150ms）：太短等于没有过渡（仍是「啪」地出现），太长会让快速滑动时
 * 每一格都在半透明状态里排队。
 *
 * **例外（票 #146 ③，命中档）**：位图在**组合期**已命中内存缓存时（`ui/CoverThumb` 的 `cachedCoverBitmap`），
 * 首帧就是那张图（`animateFloatAsState` 首帧即目标值）⇒ **既不骨架也不跑淡入**（首帧 alpha 即 1）。
 * 这是「命中就首帧有图」的必然结果（若跑淡入，首帧 alpha=0 就还是骨架），不是第三形态回归：
 * 骨架与淡入仍只在**真没缓存**那一档发生。验收时要注意：**保持组合**的暖屏观感逐字不变；
 * **重新组合**的暖屏由「骨架 + 150ms 淡入」变成「当帧即图」。
 *
 * 视觉不改：骨架仍是 `CoverThumb` 原本那层 `Color.DarkGray` 底色（本票只去掉「第三种形态」，
 * 不新定配色——配色属维护者拍板的视觉决策）。
 *
 * 本常量在 JVM 单测里只能钉住数值本身（真正的淡入发生在组合期渲染），
 * 「是否真的淡入、观感是否统一」按 SPEC 的 Testing Decisions 走手动/真机验收。
 */
const val COVER_FADE_IN_MILLIS: Int = 150
