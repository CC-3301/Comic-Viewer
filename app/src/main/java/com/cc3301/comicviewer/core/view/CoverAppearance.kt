/**
 * 封面出图口径（票 #108 E2-B；票 #145 撤掉淡入，由 [CoverAppearanceTest] 锁定）。
 *
 * 维护者现象：书柜/浏览页的封面会以三种形态混着出现——立刻就有、灰底「加载中」、以及「从无到有慢慢加载出来」。
 * 口径统一成**两态**：骨架占位（盒子的底色，位图未到位时恒在）→ 出图。
 *
 * **出图不带淡入（票 #145，维护者 2026-09-29 拍板）**：位图一到**直接出现**（本常量为 0）——
 * 不再走原先那条 150ms 的 `graphicsLayer { alpha }` 逐帧半透明合成。理由：冷启动首窗里 12~18 张封面
 * **同时**在 150ms 内做半透明合成，而当时那三个帧级打点量的都是「位图落地那一帧」（那一刻 alpha≈0、
 * 本来就便宜）⇒ 它是在构造上量不到的那部分成本。观感随之变化：「由无到有」那一下是硬切——这正是当初
 * 加淡入要消掉的东西，属维护者已拍板的视觉决策。
 * 回退成本 = 本常量加回非 0 时长（`ui/CoverThumb` 那条 `animateFloatAsState` 机制**保留**、结构不动）。
 *
 * **例外（票 #146 ③，命中档）**：位图在**组合期**已命中内存缓存时（`ui/CoverThumb` 的 `cachedCoverBitmap`），
 * 首帧就是那张图 ⇒ 首帧**不出现骨架**（又：撤淡入前这一档还意味着「不跑淡入」，现在出图本来就不淡入，
 * 这一档的差别只剩「骨架出不出现」）。这是「命中就首帧有图」的必然结果（若初值恒为 null，首帧就还是骨架），
 * 不是第三形态回归：骨架仍只在**真没缓存**那一档发生。验收时要注意（仓库把「组合」定义成 composable 的
 * **体执行次数**，即重组，见 [ScrollProbe] 的「组合次数」条）：**同一份挂载内**（重组）暖屏观感逐字不变——
 * 那种情况下 `remember(bitmapKey)` 的位图保留、根本不走这条初值；**重新挂载 / 全新组合**（返回浏览页、切容器、
 * 旋转、回看被 Lazy 回收的格子）的暖屏由「骨架 + 淡入」变成「首帧即图」（命中）或「骨架 + 硬切出图」（未命中）。
 *
 * 视觉不改：骨架仍是 `CoverThumb` 原本那层 `Color.DarkGray` 底色（本票只改出图那一下的过渡，
 * 不新定配色——配色属维护者拍板的视觉决策）。
 *
 * 本常量在 JVM 单测里只能钉住数值本身（真正的出图发生在组合期渲染），
 * 「是否真的直接出现、观感是否统一」按 SPEC 的 Testing Decisions 走手动/真机验收。
 */
